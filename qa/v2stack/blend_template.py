#!/usr/bin/env python3
"""main_v5_C + the public "0.954 recipe" notebook, rank blend 0.7 base / 0.3 ours.

GENERATED by qa/v2stack/build_kernel.py. Weight fixed 2026-10-11 before any gold-58 number was seen (same
0.3 as the 57037844 blend).
Leg 1 is our hardened main_v5_C script (md5 @@OURS_MD5@@), run unchanged; its file is the fallback.
Leg 2 is matterhorn3838/rsna-knee-v2-velciraptor-dinosaur-speed (sha256 @@NB_SHA@@): nartaa Raptor CoAtNet 384
SWA (trained with OAI data) 0.7 + heliosli compact ConvNeXt-small S6 0.3, its cells unchanged but the start time
its 8.3 h deadline counts from. Any failure, timeout, NaN or missing study in leg 2 keeps leg 1's file.
"""
import base64
import json
import os
import shutil
import subprocess
import sys
import time

import numpy as np
import pandas as pd

T0 = time.time()
W = 0.30
BASE_MIN_LEFT_S = 1.5 * 3600  # start leg 2 only if this much of the 9 h remains
TOTAL_S = 8.6 * 3600
WORK = os.environ.get("BLEND_WORK", "/kaggle/working")
OURS_ARGS = os.environ.get("BLEND_OURS_ARGS", "").split()
ID = "StudyInstanceUID"
OURS_SRC = "@@OURS_B64@@"
BASE_SRC = "@@BASE_B64@@"


def say(*a):
    print(f"[blend {time.time() - T0:7.0f}s]", *a, flush=True)


def left():
    return TOTAL_S - (time.time() - T0)


def write_atomic(df, path):
    tmp = path + ".tmp"
    df.to_csv(tmp, index=False)
    os.replace(tmp, path)


def load(path, ids, labels):
    df = pd.read_csv(path, dtype={ID: str}).set_index(ID)
    missing = set(ids) - set(df.index)
    if missing:
        raise RuntimeError(f"{os.path.basename(path)} missed {len(missing)} studies")
    df = df.loc[ids, labels]
    if not np.isfinite(df.to_numpy(np.float64)).all():
        raise RuntimeError(f"{os.path.basename(path)} predictions are not finite")
    if len(df) > 1 and (df.nunique() <= 1).any():
        raise RuntimeError(f"{os.path.basename(path)} predictions are constant in a column")
    return df.rank(pct=True)


def base_leg(ours, final, report):
    py = os.path.join(WORK, "_base", "base_v2.py")
    os.makedirs(os.path.dirname(py), exist_ok=True)
    with open(py, "wb") as f:
        f.write(base64.b64decode(BASE_SRC))
    # the base writes submission.csv (over leg 1's copy) and only then blend_receipt.json, so a receipt from this
    # run is the proof that submission.csv is the base's
    receipt = os.path.join(WORK, "blend_receipt.json")
    if os.path.exists(receipt):
        os.remove(receipt)
    say(f"leg 2: public 0.954 recipe, {left() / 3600:.2f} h left")
    t = time.time()
    subprocess.run([sys.executable, "-u", py], check=True, timeout=left() - 600, cwd=WORK,
                   env=dict(os.environ, BLEND_T0=repr(T0)))
    report["base_s"] = round(time.time() - t)
    if not os.path.exists(receipt):
        raise RuntimeError("leg 2 exited 0 without blend_receipt.json")
    rec = json.load(open(receipt))
    report["base_receipt"] = {k: rec.get(k) for k in ("weights", "rows", "raptor_failed", "ours_failed",
                                                      "raptor_seconds", "total_seconds")}
    shutil.copy(final, os.path.join(WORK, "_base.csv"))
    ids, labels = list(ours[ID]), [c for c in ours.columns if c != ID]
    base = load(os.path.join(WORK, "_base.csv"), ids, labels)
    mine = ours.set_index(ID).loc[ids, labels].rank(pct=True)
    if len(ids) > 2:
        report["spearman_base_ours"] = round(float(np.mean([base[k].corr(mine[k], method="spearman")
                                                            for k in labels])), 3)
    out = ((1 - W) * base + W * mine).reset_index()
    return out[[ID] + labels]


def main():
    os.makedirs(WORK, exist_ok=True)
    final = os.path.join(WORK, "submission.csv")
    report = {"w": W}
    ours_py = os.path.join(WORK, "_ours", "kaggle_inference.py")
    os.makedirs(os.path.dirname(ours_py), exist_ok=True)
    with open(ours_py, "wb") as f:
        f.write(base64.b64decode(OURS_SRC))
    ours_csv = os.path.join(WORK, "_ours.csv")
    say("leg 1: main_v5_C")
    rc = subprocess.call([sys.executable, ours_py, "--out", ours_csv] + OURS_ARGS, cwd=WORK)
    report.update(ours_rc=rc, ours_s=round(time.time() - T0))
    say("leg 1 exit", rc)
    if not os.path.exists(ours_csv):
        raise SystemExit(f"leg 1 wrote no file (exit {rc})")
    shutil.copy(ours_csv, final)
    ours = pd.read_csv(ours_csv, dtype={ID: str})
    out = None
    try:
        if rc != 0:
            raise RuntimeError(f"leg 1 exit {rc}; its file is kept as is")
        if left() < BASE_MIN_LEFT_S:
            raise RuntimeError(f"only {left() / 3600:.2f} h left")
        out = base_leg(ours, final, report)
    except Exception as e:  # noqa: BLE001 - leg 1's file stands
        report.update(blended=False, base_error=repr(e)[:300])
        say("leg 2 FAILED, main_v5_C kept:", repr(e))
    if out is None:
        shutil.copy(ours_csv, final)
    else:
        write_atomic(out, final)
        report["blended"] = True
        say(f"blended {len(out)} studies at our weight {W}")
    report["total_s"] = round(time.time() - T0)
    with open(os.path.join(WORK, "v2stack_report.json"), "w") as f:
        json.dump(report, f, indent=1)
    say("done", report)
    return rc


if __name__ == "__main__":
    _rc = main()
    sys.stdout.flush()
    os._exit(_rc)
