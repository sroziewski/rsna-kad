"""Build qa/v2stack/kernel_blend/: main_v5_C + the public "0.954 recipe" notebook
(matterhorn3838/rsna-knee-v2-velciraptor-dinosaur-speed: nartaa Raptor CoAtNet 384 SWA, OAI-trained, rank-blended
0.7/0.3 with heliosli's compact ConvNeXt-small S6), from the hardened notebook and that notebook's cells.

The public cells run unchanged except one line: NB_T0 (which its 8.3 h deadline counts from) is taken from the
wrapper's start, because our leg runs first.  `--fake ROOT` rewrites /kaggle/ and /tmp paths for the gold-58 test.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
NB = HERE / "src" / "rsna-knee-v2-velciraptor-dinosaur-speed.ipynb"
NB_SHA = "d358d04538df4abfbdc5a69b48bd3e3491d5cd93de24d2be825f3e05e61d0af1"
T0_LINE = "NB_T0 = time.time()"
T0_PATCH = "NB_T0 = float(os.environ.get('BLEND_T0') or time.time())  # [v2stack] wrapper start: our leg ran first"

ap = argparse.ArgumentParser()
ap.add_argument("--fake", help="test tree root replacing /kaggle and /tmp")
ap.add_argument("--out", default=str(HERE / "kernel_blend"))
ap.add_argument("--weights-dataset", default="sroziews/rsna-kad-weights-v5c", help="leg 1 bundle (qa/oai: OAI students)")
ap.add_argument("--kernel-id", default="sroziews/rsna-kad-v5c-v2stack")
ap.add_argument("--nb", default=str(NB), help="base notebook (qa/v3stack: heliosli R7 0.957)")
ap.add_argument("--nb-sha", default=NB_SHA)
ap.add_argument("--base-datasets", nargs="+", default=["nartaa/rsna-knee-publication-swa-weights-20261007",
                "heliosli/rsna-knee-compact-v1", "heliosli/rsna-orthofoundation-fold0-epoch7-20261004"])
ap.add_argument("--w-per", help='JSON {finding: our weight} overriding W for those findings (qa/v4pf)')
ap.add_argument("--generic-nb", action="store_true",
                help="base notebook of any layout (qa/r6base: goodpjw2008's 0.958): every %%%%writefile cell becomes a "
                     "file write, the other code cells run in order; NB_T0 must occur once")
a = ap.parse_args()
W_PER = json.loads(a.w_per) if a.w_per else None

ours = (HERE.parents[1] / "qa/main_v5/kernel_v5c/kaggle_inference.py").read_bytes()
md5 = hashlib.md5(ours).hexdigest()
assert md5.startswith("b328ad1a"), md5
NB = Path(a.nb)
nb_bytes = NB.read_bytes()
nb_sha = hashlib.sha256(nb_bytes).hexdigest()
assert nb_sha == a.nb_sha, nb_sha
cells = ["".join(c["source"]) for c in json.loads(nb_bytes)["cells"] if c["cell_type"] == "code"]


def fake(text):
    if not a.fake:
        return text
    return text.replace("/kaggle/", a.fake + "/").replace("'/tmp", f"'{a.fake}/tmp")


def b64(s):
    return base64.b64encode(s.encode()).decode()


if a.generic_nb:
    assert sum(c.count(T0_LINE) for c in cells) == 1, "NB_T0 line not found exactly once"
    parts = []
    for c in cells:
        if c.startswith("%%writefile "):
            head, body = c.split("\n", 1)
            path = head.split(None, 1)[1].strip()
            parts.append(fake(f"os.makedirs(os.path.dirname({path!r}), exist_ok=True)\n"
                              f"open({path!r}, 'w', encoding='utf-8').write(base64.b64decode({b64(fake(body))!r}).decode())"))
        else:
            assert not any(ln.lstrip().startswith(("!", "%")) for ln in c.splitlines()), c[:80]
            parts.append(fake(c.replace(T0_LINE, T0_PATCH)))
    base = "\n\n".join([
        f"# GENERATED by qa/v2stack/build_kernel.py --generic-nb from {NB.name} (sha256 {nb_sha}); code cells verbatim "
        "but NB_T0, %%writefile cells as file writes",
        "import base64\nimport os\ndisplay = print",
        *parts,
    ])
else:
    assert len(cells) == 5 and cells[0].startswith("%%writefile /tmp/raptor_run.py\n"), [c[:60] for c in cells]
    assert cells[1].count(T0_LINE) == 1
    raptor = fake(cells[0].split("\n", 1)[1])
    base = "\n\n".join([
        f"# GENERATED by qa/v2stack/build_kernel.py from {NB.name} (sha256 {nb_sha}); cells 1-4 verbatim but NB_T0",
        "import base64\ndisplay = print",
        fake(f"open('/tmp/raptor_run.py', 'w', encoding='utf-8').write(base64.b64decode({base64.b64encode(raptor.encode()).decode()!r}).decode())"),
        fake(cells[1].replace(T0_LINE, T0_PATCH)),
        *[fake(c) for c in cells[2:]],
    ])
text = ((HERE / "blend_template.py").read_text()
        .replace("@@OURS_MD5@@", md5)
        .replace("@@NB_SHA@@", nb_sha)
        .replace("@@OURS_B64@@", base64.b64encode(ours).decode())
        .replace("@@BASE_B64@@", base64.b64encode(base.encode()).decode()))
if W_PER:
    for old, new in (
            ("W = 0.30\n", f"W = 0.30\nW_PER = {W_PER!r}  # [v4pf] our weight for these findings, W for the rest\n"),
            ('report = {"w": W}', 'report = {"w": W, "w_per": W_PER}'),
            ("    out = ((1 - W) * base + W * mine).reset_index()\n",
             "    assert set(W_PER) <= set(labels), W_PER\n"
             "    w = pd.Series({k: W_PER.get(k, W) for k in labels})\n"
             "    out = ((1 - w) * base + w * mine).reset_index()\n")):
        assert text.count(old) == 1, old
        text = text.replace(old, new)
out = Path(a.out)
out.mkdir(parents=True, exist_ok=True)
(out / "blend_v2stack.py").write_text(text)
(out / "base_v2.py").write_text(base)  # readable copy for review; the kernel embeds it
meta = {
    "id": a.kernel_id,
    "title": a.kernel_id.split("/")[1],
    "code_file": "blend_v2stack.py",
    "language": "python",
    "kernel_type": "script",
    "is_private": True,
    "enable_gpu": True,
    "enable_tpu": False,
    "enable_internet": False,
    "dataset_sources": [a.weights_dataset, *a.base_datasets],
    "competition_sources": ["rsna-knee-abnormality-detection"],
    "kernel_sources": [],
    "model_sources": [],
    # the image main_v5_C scored 0.948 on, and the one the public notebook runs on
    "docker_image": "gcr.io/kaggle-private-byod/python@sha256:37c64f7dd9c54116ecd1bcc88817c5469b88387388fade02bfa8bf3fc647d461",
    "machine_shape": "NvidiaTeslaT4",
}
(out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
print("built", out / "blend_v2stack.py", len(text), "bytes; ours md5", md5, "; notebook sha256", nb_sha,
      "; blend md5", hashlib.md5(text.encode()).hexdigest())
